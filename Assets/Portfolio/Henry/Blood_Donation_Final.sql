DROP TABLE DONOR CASCADE CONSTRAINTS;
DROP TABLE STAFF CASCADE CONSTRAINTS;
DROP TABLE HOSPITAL CASCADE CONSTRAINTS;
DROP TABLE HEALTH_SCREENING CASCADE CONSTRAINTS;
DROP TABLE DONATION CASCADE CONSTRAINTS;
DROP TABLE BLOOD_INVENTORY CASCADE CONSTRAINTS;
DROP TABLE BLOOD_REQUEST CASCADE CONSTRAINTS;
DROP TABLE REQUEST_ITEM CASCADE CONSTRAINTS;
DROP TABLE BLOOD_ISSUE_STATUS CASCADE CONSTRAINTS;


CREATE TABLE DONOR (
    Donor_ID VARCHAR2(20) NOT NULL PRIMARY KEY,
    Full_Name VARCHAR2(100) NOT NULL,
    IC_Passport VARCHAR2(50) NOT NULL unique,
    Date_Of_Birth DATE NOT NULL,
    Gender VARCHAR2(20) CHECK (Gender IN ('Male', 'Female')) NOT NULL, 
    Phone_Number VARCHAR2(20) NOT NULL,
    Address VARCHAR2(200) NOT NULL,
    Blood_Type VARCHAR2(3) CHECK (Blood_Type IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
    Registration_Date DATE DEFAULT SYSDATE NOT NULL 
);


CREATE TABLE STAFF (
    Staff_ID VARCHAR2(20) NOT NULL PRIMARY KEY,
    First_Name VARCHAR2(50) NOT NULL,
    Last_Name VARCHAR2(50) NOT NULL,
    Role VARCHAR2(50) NOT NULL CHECK(Role IN ('Administrator','Nurse','Doctor','Lab Technician')),
    Phone_Number VARCHAR2(20) NOT NULL,
    Email VARCHAR2(100) NOT NULL,
    CONSTRAINT chk_email_format CHECK (Email LIKE '%@%._%')
);

CREATE TABLE HOSPITAL (
    Hospital_ID VARCHAR2(20) NOT NULL PRIMARY KEY,
    Hospital_Name VARCHAR2(100) NOT NULL,
    Address VARCHAR2(200) NOT NULL,
    Contact_Number VARCHAR2(20) NOT NULL,
    Email VARCHAR2(100) UNIQUE NOT NULL,
    CONSTRAINT chk_hospital_email_format CHECK (Email LIKE '%@%._%')
);

CREATE TABLE HEALTH_SCREENING (
    Screening_ID VARCHAR2(20) NOT NULL PRIMARY KEY,
    Donor_ID VARCHAR2(20) NOT NULL,
    Staff_ID VARCHAR2(20) NOT NULL,
    Screening_Date DATE DEFAULT SYSDATE NOT NULL,
    Weight NUMBER(5,2) NOT NULL,
    Blood_Pressure VARCHAR2(10) NOT NULL,
    Haemoglobin_Level NUMBER(4,1) NOT NULL,
    Eligibility_Status VARCHAR2(20) DEFAULT 'Pending' NOT NULL CHECK (Eligibility_Status IN ('Pending','Eligible', 'Not Eligible')), -- AUTO Y IF NOT FILL ANYTHING, ONLY HAVE 2 OPTION Y OR N
    Rejection_Reason VARCHAR2(200),
    CONSTRAINT fk_screening_donor FOREIGN KEY (Donor_ID) REFERENCES DONOR(Donor_ID),
    CONSTRAINT fk_screening_staff FOREIGN KEY (Staff_ID) REFERENCES STAFF(Staff_ID)
);

CREATE TABLE DONATION (
    Donation_ID VARCHAR2(20) NOT NULL PRIMARY KEY,
    Donor_ID VARCHAR2(20) NOT NULL,
    Screening_ID VARCHAR2(20) NOT NULL,
    Staff_ID VARCHAR2(20) NOT NULL,
    Donation_Date DATE DEFAULT SYSDATE NOT NULL,
    Donation_Type VARCHAR2(20) NOT NULL CHECK (Donation_Type IN ('Whole Blood', 'Plasma', 'Platelet', 'Double Red Cell')), -- THE MOST ACCURATE IS THIS 4 TYPE
    Volume_ml NUMBER(4,0) NOT NULL CHECK (Volume_ml BETWEEN 200 AND 600), --NORMAL BLOOD PACK 350ML OR 450ML 
    CONSTRAINT fk_donation_donor FOREIGN KEY (Donor_ID) REFERENCES DONOR(Donor_ID),
    CONSTRAINT fk_donation_screening FOREIGN KEY (Screening_ID) REFERENCES HEALTH_SCREENING(Screening_ID),
    CONSTRAINT fk_donation_staff FOREIGN KEY (Staff_ID) REFERENCES STAFF(Staff_ID)
);

--Need calculate manually, donation - blood_issued
CREATE TABLE BLOOD_INVENTORY (
    Inventory_ID VARCHAR2(20) NOT NULL PRIMARY KEY,
    Donation_ID VARCHAR2(20) NOT NULL,
    Blood_Type VARCHAR2(3) NOT NULL CHECK (Blood_Type IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
    Remaining_Volume_mL NUMBER(10, 2) CHECK(Remaining_Volume_mL >= 0), 
    Expiry_Date DATE NOT NULL,
    Storage_Location VARCHAR2(100),
    Current_Status VARCHAR2(20) DEFAULT 'Available' CHECK (Current_Status IN ('Available','Issued','Partially Issued','Expired')),
    CONSTRAINT fk_inventory_donation FOREIGN KEY (Donation_ID) REFERENCES DONATION(Donation_ID)
);

CREATE TABLE BLOOD_REQUEST (
    Request_ID VARCHAR2(20) NOT NULL PRIMARY KEY,
    Hospital_ID VARCHAR2(20) NOT NULL,
    Request_Date DATE DEFAULT SYSDATE NOT NULL,
    Priority VARCHAR2(20) NOT NULL CHECK (Priority IN ('Routine','Emergency')),
    CONSTRAINT fk_request_hospital FOREIGN KEY (Hospital_ID) REFERENCES HOSPITAL(Hospital_ID)
);

CREATE TABLE REQUEST_ITEM (
    Request_Item_ID VARCHAR2(20) NOT NULL PRIMARY KEY,
    Request_ID VARCHAR2(20) NOT NULL,
    Blood_Type VARCHAR2(3) NOT NULL CHECK (Blood_Type IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
    Requested_Volume_mL NUMBER(10,2) NOT NULL CHECK (Requested_Volume_mL >= 1), --IF REQUEST, MUST BE 1 OR ELSE WON'T HAVE THIS REQUEST :)
    CONSTRAINT fk_requestitem_request FOREIGN KEY (Request_ID) REFERENCES BLOOD_REQUEST(Request_ID)
);

CREATE TABLE BLOOD_ISSUE_STATUS (
    BLOOD_ISSUE_ID VARCHAR(20) NOT NULL PRIMARY KEY,
    Request_Item_ID VARCHAR2(20) NOT NULL,
    Inventory_ID VARCHAR2(20),
    Staff_ID VARCHAR2(20) NOT NULL,
    Issue_Volume_mL NUMBER(3,0) NOT NULL CHECK (Issue_Volume_mL >= 0),
    Issue_Status VARCHAR2(20) DEFAULT 'Pending' CHECK (Issue_Status IN ('Pending', 'Issued', 'Rejected')) NOT NULL,
    CONSTRAINT fk_issue_inventory FOREIGN KEY (Inventory_ID) REFERENCES BLOOD_INVENTORY(Inventory_ID),
    CONSTRAINT fk_issue_request_item FOREIGN KEY (Request_Item_ID) REFERENCES REQUEST_ITEM(Request_Item_ID),
    CONSTRAINT fk_issue_staff FOREIGN KEY (Staff_ID) REFERENCES STAFF(Staff_ID)
);

